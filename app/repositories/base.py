"""
Base Repository Interfaces (Protocols / Abstract Classes)
These interfaces define the data access contract.
In Phase 1, Mock Repositories implement these methods using memory/session data.
In Phase 2, SQL Database Repositories will implement these exact methods using SQLAlchemy / raw SQL.
"""

from typing import Protocol, List, Optional, Dict, Any


class IUserRepository(Protocol):
    def get_by_id(self, user_id: str) -> Optional[Dict[str, Any]]: ...
    def get_by_email(self, email: str) -> Optional[Dict[str, Any]]: ...
    def create(self, user_data: Dict[str, Any]) -> Dict[str, Any]: ...
    def update(self, user_id: str, updates: Dict[str, Any]) -> Optional[Dict[str, Any]]: ...
    def get_all(self, role: Optional[str] = None) -> List[Dict[str, Any]]: ...
    def add_address(self, user_id: str, address_data: Dict[str, Any]) -> Dict[str, Any]: ...
    def get_addresses(self, user_id: str) -> List[Dict[str, Any]]: ...


class IProductRepository(Protocol):
    def get_by_id(self, product_id: str) -> Optional[Dict[str, Any]]: ...
    def get_by_slug(self, slug: str) -> Optional[Dict[str, Any]]: ...
    def get_all(
        self,
        category_slug: Optional[str] = None,
        brand_slug: Optional[str] = None,
        seller_id: Optional[str] = None,
        query: Optional[str] = None,
        min_price: Optional[float] = None,
        max_price: Optional[float] = None,
        sort_by: Optional[str] = None,
        is_featured: Optional[bool] = None,
        is_active: Optional[bool] = True,
        limit: Optional[int] = None,
    ) -> List[Dict[str, Any]]: ...
    def create(self, product_data: Dict[str, Any]) -> Dict[str, Any]: ...
    def update(self, product_id: str, updates: Dict[str, Any]) -> Optional[Dict[str, Any]]: ...
    def delete(self, product_id: str) -> bool: ...


class IOrderRepository(Protocol):
    def get_by_id(self, order_id: str) -> Optional[Dict[str, Any]]: ...
    def get_by_customer(self, customer_id: str) -> List[Dict[str, Any]]: ...
    def get_by_seller(self, seller_id: str) -> List[Dict[str, Any]]: ...
    def get_all(self, status: Optional[str] = None) -> List[Dict[str, Any]]: ...
    def create(self, order_data: Dict[str, Any]) -> Dict[str, Any]: ...
    def update_status(self, order_id: str, status: str, timeline_note: Optional[str] = None) -> Optional[Dict[str, Any]]: ...


class ISellerRepository(Protocol):
    def get_by_id(self, seller_id: str) -> Optional[Dict[str, Any]]: ...
    def get_by_slug(self, slug: str) -> Optional[Dict[str, Any]]: ...
    def get_by_email(self, email: str) -> Optional[Dict[str, Any]]: ...
    def get_all(self, status: Optional[str] = None) -> List[Dict[str, Any]]: ...
    def create(self, seller_data: Dict[str, Any]) -> Dict[str, Any]: ...
    def update(self, seller_id: str, updates: Dict[str, Any]) -> Optional[Dict[str, Any]]: ...


class ICategoryRepository(Protocol):
    def get_by_id(self, cat_id: str) -> Optional[Dict[str, Any]]: ...
    def get_by_slug(self, slug: str) -> Optional[Dict[str, Any]]: ...
    def get_all(self) -> List[Dict[str, Any]]: ...
    def create(self, cat_data: Dict[str, Any]) -> Dict[str, Any]: ...


class ICouponRepository(Protocol):
    def get_by_code(self, code: str) -> Optional[Dict[str, Any]]: ...
    def get_all(self) -> List[Dict[str, Any]]: ...
    def create(self, coupon_data: Dict[str, Any]) -> Dict[str, Any]: ...


class INotificationRepository(Protocol):
    def get_for_user(self, user_id: str, role: str) -> List[Dict[str, Any]]: ...
    def create(self, notif_data: Dict[str, Any]) -> Dict[str, Any]: ...
    def mark_read(self, notif_id: str) -> bool: ...


class IReviewRepository(Protocol):
    def get_by_product(self, product_id: str) -> List[Dict[str, Any]]: ...
    def get_by_user(self, user_id: str) -> List[Dict[str, Any]]: ...
    def get_by_seller(self, seller_id: str) -> List[Dict[str, Any]]: ...
    def get_all(self) -> List[Dict[str, Any]]: ...
    def create(self, review_data: Dict[str, Any]) -> Dict[str, Any]: ...
    def respond_to_review(self, review_id: str, response: str) -> bool: ...


class IInventoryRepository(Protocol):
    def get_logs_by_seller(self, seller_id: str) -> List[Dict[str, Any]]: ...
    def adjust_stock(self, product_id: str, quantity_change: int, reason: str, adjusted_by: str) -> Optional[Dict[str, Any]]: ...


class IPayoutRepository(Protocol):
    def get_by_seller(self, seller_id: str) -> List[Dict[str, Any]]: ...
    def get_all(self) -> List[Dict[str, Any]]: ...
    def create_request(self, payout_data: Dict[str, Any]) -> Dict[str, Any]: ...
    def update_status(self, payout_id: str, status: str) -> Optional[Dict[str, Any]]: ...
